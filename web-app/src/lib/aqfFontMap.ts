export function getSurahCalligraphyChar(surahId: number): string {
  if (surahId >= 1 && surahId <= 114) {
    return String.fromCharCode(SURAH_GLYPH_CODES[surahId - 1])
  }
  return ""
}

/**
 * Calligraphic Bismillah Glyphs in AQF_BSML:
 * 0xFC20, 0xFC22, 0xFC23 are full ornate Bismillah calligraphies
 */
export const AQF_BISMILLAH_CHAR = String.fromCharCode(0xfc23)
